def watermark(operator, session_id, scope="OWN / AUTHORIZED DATA ONLY"):
    ts = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%SZ")
    return "PasswordGuardian Report | operator: {} | session: {} | {}".format(
        operator, session_id, ts
    )


def build_data(meta, summary, items):
    return {
        "meta": meta,
        "summary": summary,
        "items": items,
    }


def _esc(v):
    return html.escape(str(v if v is not None else ""), quote=True)


def build_html(meta, summary, items):
    wm = watermark(meta["operator"], meta["session_id"])
    rows = []
    for it in items:
        status = "cracked" if it.get("candidate") else ("unresolved" if it.get("resolved") is not False else "pending")
        rows.append(
            "<tr>"
            "<td>{}</td><td><code>{}</code></td><td>{}</td><td>{}</td>"
            "<td>{}</td></tr>".format(
                _esc(it.get("pos", "")),
                _esc(it.get("token", "")),
                _esc(" / ".join(it.get("algos") or [])),
                _esc(it.get("salt") or ""),
                _esc(it.get("candidate") or ""),
            )
        )
    table = "<table><thead><tr><th>#</th><th>Hash</th><th>Algorithm</th><th>Salt</th><th>Found plaintext</th></tr></thead><tbody>{}</tbody></table>".format(
        "".join(rows)
    )
    stat_cells = "".join(
        "<b>{}</b> {}".format(_esc(str(v)), _esc(k)) if not isinstance(v, str) else "<b>{}</b> <i>{}</i>".format(_esc(v), k)
        for k, v in summary.items()
        if k not in ("found_map", "attempted")
    )
    return HTML_TEMPLATE.format(
        watermark=_esc(wm),
        scope=_esc(meta.get("scope", "OWN / AUTHORIZED DATA ONLY")),
        operator=_esc(meta["operator"]),
        summary=stat_cells,
        table=table,
    )


