def write_csv(path, items):
    with open(path, "w", newline="", encoding="utf-8-sig") as fh:
        writer = csv.writer(fh)
        writer.writerow(["#", "hash", "algorithms", "salt", "status", "plaintext"])
        for it in items:
            writer.writerow(
                [
                    it.get("pos", ""),
                    it.get("token", ""),
                    " / ".join(it.get("algos") or []),
                    it.get("salt") or "",
                    "cracked" if it.get("candidate") else "unresolved",
                    it.get("candidate") or "",
                ]
            )


def write_json(path, data):
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(data, fh, indent=2)


def save_encrypted_bundle(path, data, local_machine=False):
    if not ws.bundle_available():
        raise RuntimeError("encrypted bundles require Windows DPAPI")
    payload = json.dumps(data).encode("utf-8")
    ws.save_bundle(path, payload, local_machine=local_machine)
    return path


def load_encrypted_bundle(path):
    if not ws.bundle_available():
        raise RuntimeError("encrypted bundles require Windows DPAPI")
    raw = ws.load_bundle(path)
    return json.loads(raw.decode("utf-8"))