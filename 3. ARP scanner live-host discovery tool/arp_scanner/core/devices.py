def lookup_vendor(mac: str) -> str | None:
    """Return the vendor name for a MAC address, or None when unknown."""
    if not mac:
        return None
    normalized = normalize_mac(str(mac).strip())
    if normalized is None:
        return None
    return OUI_VENDORS.get(oui_prefix(normalized))