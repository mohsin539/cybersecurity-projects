/**
 * Format renderers.
 *
 * All five writers consume the same `ReportModel`, so every format carries
 * identical figures. Shared concerns handled here:
 *
 *   CSV  - RFC 4180 quoting, BOM for Excel, formula-injection neutralisation.
 *   XLSX - styled workbook, frozen headers, autofilter, print setup, metadata.
 *   HTML - self-contained, offline-capable, strict CSP, fully escaped output.
 *   PDF  - vector text (selectable/searchable), paginated tables, embedded PNG.
 *   JSON - the raw model, for machine consumption and diffing.
 *
 * Injection defences (OWASP A03:2021):
 *   - Every cell that originates from user input is HTML-escaped before it can
 *     reach the HTML renderer; no `innerHTML` is ever used server-side.
 *   - Cells beginning with = + - @ TAB CR are prefixed with an apostrophe in
 *     CSV/XLSX so a spreadsheet cannot be coerced into evaluating a formula.
 *   - PDF text is drawn with the text API, never interpreted.
 */

import ExcelJS from 'exceljs';
import PDFDocument from 'pdfkit';
import { REPORT_FORMATS_MIME, type ReportFormat } from '@prismforge/shared';
import type { ReportModel, ReportSection } from './report.service.js';

export interface RenderedReport {
  body: Buffer;
  mime: string;
  extension: string;
  /** Suggested download filename, without directory components. */
  filename: string;
}

export type ReportRenderer = (model: ReportModel, filenameBase: string) => RenderedReport | Promise<RenderedReport>;

// ---------------------------------------------------------------------------
// Shared helpers
// ---------------------------------------------------------------------------

/** Neutralises spreadsheet formula injection. */
function neutraliseFormula(value: string): string {
  return /^[=+\-@\t\r]/.test(value) ? `'${value}` : value;
}

function cellText(value: string | number | null): string {
  if (value === null || value === undefined) return '';
  return neutraliseFormula(String(value));
}

export function slug(input: string): string {
  return input
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 60);
}

export function stamp(model: ReportModel): string {
  return model.meta.generatedAt.replace(/[:.]/g, '-').replace('T', '_').slice(0, 19);
}

function baseName(model: ReportModel): string {
  return `prismforge-${slug(model.meta.subject)}-${stamp(model)}`;
}

/** Escapes the five XML-significant characters. */
function esc(value: unknown): string {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}

