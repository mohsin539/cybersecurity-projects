const BRAND_DARK = 'FF1E1B4B';
const BRAND_ACCENT = 'FF7C3AED';
const BRAND_LIGHT = 'FFF5F3FF';

export const renderXlsx: ReportRenderer = async (model) => {
  const wb = new ExcelJS.Workbook();
  wb.creator = 'PrismForge Reporting Engine';
  wb.lastModifiedBy = model.meta.generatedBy.email;
  wb.created = new Date(model.meta.generatedAt);
  wb.modified = new Date();
  wb.title = model.meta.title;
  wb.subject = model.meta.subject;
  wb.description = model.meta.provenance;
  wb.keywords = `ISO27001,NIST,OWASP,audit,${model.meta.classification}`;
  wb.company = model.meta.organisation;
  wb.category = 'Compliance reporting';

  // ---- Cover sheet -----------------------------------------------------
  const cover = wb.addWorksheet('Report', {
    views: [{ showGridLines: false }],
    pageSetup: { orientation: 'portrait', fitToPage: true, fitToWidth: 1, fitToHeight: 0 },
  });

  cover.columns = [{ width: 34 }, { width: 84 }];
  cover.mergeCells('A1:B2');
  const titleCell = cover.getCell('A1');
  titleCell.value = model.meta.title;
  titleCell.font = { size: 18, bold: true, color: { argb: 'FFFFFFFF' } };
  titleCell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_DARK } };
  titleCell.alignment = { vertical: 'middle', horizontal: 'left', indent: 1 };
  cover.getRow(1).height = 30;
  cover.getRow(2).height = 12;

  const metaRows: Array<[string, string]> = [
    ['Organisation', model.meta.organisation],
    ['Classification', model.meta.classification],
    ['Generated at (UTC)', model.meta.generatedAt],
    ['Generated by', `${model.meta.generatedBy.email} (${model.meta.generatedBy.role})`],
    ['Correlation id', model.meta.correlationId],
    ['Schema version', model.schemaVersion],
    ['Retention until', model.meta.retentionUntil],
    ['Provenance', model.meta.provenance],
  ];
  cover.addRow([]);
  metaRows.forEach(([k, v], i) => {
    const row = cover.addRow([k, v]);
    row.getCell(1).font = { bold: true, color: { argb: BRAND_DARK } };
    row.getCell(2).alignment = { wrapText: true, vertical: 'top' };
    if (i % 2 === 1) {
      row.eachCell((c) => {
        c.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_LIGHT } };
      });
    }
  });

  cover.addRow([]);
  cover.addRow(['Key figures']).font = { bold: true, size: 13, color: { argb: BRAND_DARK } };
  model.headline.forEach((h) => {
    const row = cover.addRow([h.label, h.value]);
    row.getCell(1).font = { bold: true };
    row.getCell(2).font = { bold: true, color: { argb: BRAND_ACCENT } };
  });

  if (model.chain) {
    cover.addRow([]);
    cover.addRow(['Audit chain integrity']).font = { bold: true, size: 13, color: { argb: BRAND_DARK } };
    cover.addRow(['Verified', model.chain.verified ? 'PASS' : 'FAIL']);
    cover.addRow(['Entries verified', model.chain.entries]);
    cover.addRow(['Chain head hash', model.chain.headHash ?? '-']);
    cover.addRow(['Discrepancies', model.chain.errors.length]);
  }

  if (model.notes.length) {
    cover.addRow([]);
    cover.addRow(['Notes']).font = { bold: true, size: 13, color: { argb: BRAND_DARK } };
    for (const n of model.notes) {
      const row = cover.addRow([n]);
      row.getCell(1).alignment = { wrapText: true, vertical: 'top' };
      cover.mergeCells(`A${row.number}:B${row.number}`);
    }
  }

  // ---- Data sheets -----------------------------------------------------
  model.sections.forEach((section, index) => {
    const sheet = wb.addWorksheet(`${index + 1}. ${section.heading}`.slice(0, 31), {
      views: [{ state: 'frozen', ySplit: 1 }],
      pageSetup: {
        orientation: section.columns.length > 6 ? 'landscape' : 'portrait',
        fitToPage: true,
        fitToWidth: 1,
        fitToHeight: 0,
        margins: { left: 0.4, right: 0.4, top: 0.6, bottom: 0.6, header: 0.3, footer: 0.3 },
      },
    });

    sheet.columns = section.columns.map((c) => ({
      header: c.label,
      key: c.key,
      width: c.width ?? Math.min(Math.max(c.label.length + 6, 14), c.wrap ? 48 : 30),
    }));

    const header = sheet.getRow(1);
    header.height = 24;
    header.font = { bold: true, color: { argb: 'FFFFFFFF' }, size: 11 };
    header.alignment = { vertical: 'middle', horizontal: 'center', wrapText: true };
    header.eachCell((cell) => {
      cell.fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: BRAND_DARK } };
      cell.border = { bottom: { style: 'medium', color: { argb: BRAND_ACCENT } } };
    });

    for (const row of section.rows) {
      const values: Record<string, string | number> = {};
      for (const c of section.columns) {
        const raw = row[c.key];
        values[c.key] = typeof raw === 'number' ? raw : cellText(raw ?? '');
      }
      const added = sheet.addRow(values);
      added.alignment = { vertical: 'top', wrapText: false };
      added.eachCell((cell, col) => {
        const def = section.columns[col - 1];
        cell.alignment = { vertical: 'top', horizontal: def?.align ?? 'left', wrapText: Boolean(def?.wrap) };
        if (typeof cell.value === 'number') cell.numFmt = '#,##0';
      });
    }

    if (section.rows.length > 0) {
      sheet.autoFilter = {
        from: { row: 1, column: 1 },
        to: { row: 1, column: section.columns.length },
      };
    }

    sheet.headerFooter = {
      oddFooter: `${model.meta.classification} - ${esc(model.meta.title)} - page &P of &N`,
    };
  });

  const buffer = await wb.xlsx.writeBuffer();
  return {
    body: Buffer.from(buffer),
    mime: REPORT_FORMATS_MIME.xlsx,
    extension: 'xlsx',
    filename: `${baseName(model)}.xlsx`,
  };
};

