const INK = '#1e1b4b';
const ACCENT = '#7c3aed';
const MUTED = '#64748b';
const LINE = '#e2e8f0';

export const renderPdf: ReportRenderer = async (model) => {
  const doc = new PDFDocument({
    size: 'A4',
    margins: { top: 54, bottom: 54, left: 46, right: 46 },
    info: {
      Title: model.meta.title,
      Author: model.meta.generatedBy.email,
      Subject: `${model.meta.subject} - ${model.meta.classification}`,
      Keywords: `ISO27001,NIST,OWASP,${model.meta.classification}`,
      Creator: 'PrismForge Reporting Engine',
      CreationDate: new Date(model.meta.generatedAt),
    },
  });

  const chunks: Buffer[] = [];
  const finished = new Promise<Buffer>((resolve, reject) => {
    doc.on('data', (c: Buffer) => chunks.push(c));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', reject);
  });

  const pageWidth = doc.page.width - 92;

  // ---- Cover -----------------------------------------------------------
  doc.rect(0, 0, doc.page.width, 190).fill(INK);
  doc.rect(0, 182, doc.page.width, 8).fill(ACCENT);

  doc.fillColor('#ffffff').fontSize(9).font('Helvetica-Bold');
  doc.text(model.meta.organisation.toUpperCase(), 46, 44, { characterSpacing: 1.6 });
  doc.fontSize(23).font('Helvetica-Bold').text(model.meta.title, 46, 62, { width: pageWidth });
  doc.fontSize(9).font('Helvetica').fillColor('#c7d2fe');
  doc.text(`${model.meta.generatedBy.email}  -  ${model.meta.generatedAt}  -  schema v${model.schemaVersion}`, 46, 140);

  // Classification banner
  const bannerText = `CLASSIFICATION: ${model.meta.classification}    |    SUBJECT: ${model.meta.subject}`;
  doc.roundedRect(46, 206, pageWidth, 24, 6).fill('#f5f3ff');
  doc.fillColor(ACCENT).fontSize(8.5).font('Helvetica-Bold');
  doc.text(bannerText, 56, 213, { width: pageWidth - 20 });

  if (model.chain) {
    const y = 242;
    const ok = model.chain.verified;
    doc.roundedRect(46, y, pageWidth, 26, 6).fill(ok ? '#ecfdf5' : '#fef2f2');
    doc.fillColor(ok ? '#047857' : '#b91c1c').fontSize(9.5).font('Helvetica-Bold');
    doc.text(
      ok
        ? `Audit chain integrity: VERIFIED - ${model.chain.entries} entries, ${model.chain.errors.length} discrepancies`
        : `Audit chain integrity: FAILURE - ${model.chain.errors.length} discrepancies detected`,
      56,
      y + 8,
      { width: pageWidth - 20 },
    );
  }

  // ---- Headline grid ---------------------------------------------------
  let y = model.chain ? 284 : 250;
  doc.font('Helvetica-Bold').fontSize(10).fillColor(INK).text('KEY FIGURES', 46, y);
  y += 16;

  const cols = 2;
  const colW = (pageWidth - 12) / cols;
  model.headline.forEach((h, i) => {
    const cx = 46 + (i % cols) * (colW + 12);
    const cy = y + Math.floor(i / cols) * 34;
    if (cx + colW > doc.page.width - 46) return;
    doc.roundedRect(cx, cy, colW, 29, 5).fill('#ffffff');
    doc.rect(cx, cy, 3, 29).fill(ACCENT);
    doc.fillColor(MUTED).fontSize(7.5).font('Helvetica-Bold');
    doc.text(h.label.toUpperCase(), cx + 9, cy + 6, { width: colW - 16, characterSpacing: 0.6 });
    doc.fillColor(INK).fontSize(9.5).font('Helvetica');
    doc.text(String(h.value), cx + 9, cy + 16, { width: colW - 16, ellipsis: true, lineBreak: false });
  });
  y += Math.ceil(model.headline.length / cols) * 34 + 10;

  // ---- Snapshot --------------------------------------------------------
  if (model.snapshot) {
    const match = /^data:image\/png;base64,(.+)$/.exec(model.snapshot);
    if (match) {
      const img = Buffer.from(match[1]!, 'base64');
      const maxW = 240;
      const h = 190;
      if (y + h < doc.page.height - 70) {
        try {
          doc.image(img, 46, y, { fit: [maxW, h] });
          doc.fillColor(MUTED).fontSize(7.5).font('Helvetica-Oblique');
          doc.text('Client-rendered 3D preview captured at time of report generation.', 300, y + 6, {
            width: pageWidth - 254,
          });
          doc.fillColor(INK).fontSize(9).font('Helvetica-Bold').text('Configuration summary', 300, y + 24);
          doc.fillColor('#334155').fontSize(8.5).font('Helvetica');
          const specSummary = `${model.headline[0]?.value ?? ''} - ${model.headline[2]?.value ?? ''}`;
          doc.text(specSummary, 300, y + 38, { width: pageWidth - 254 });
          y += h + 14;
        } catch {
          /* a malformed snapshot must never abort the report */
        }
      }
    }
  }

  // ---- Sections --------------------------------------------------------
  for (const section of model.sections) {
    if (y > doc.page.height - 150) {
      doc.addPage();
      y = 56;
    }
    y = drawSection(doc, section, y, pageWidth);
  }

  // ---- Notes & footer --------------------------------------------------
  if (model.notes.length) {
    if (y > doc.page.height - 140) {
      doc.addPage();
      y = 56;
    }
    doc.font('Helvetica-Bold').fontSize(10).fillColor(INK).text('NOTES & QUALIFICATIONS', 46, y + 8);
    y += 24;
    doc.font('Helvetica').fontSize(8).fillColor('#334155');
    for (const note of model.notes) {
      const h = doc.heightOfString(note, { width: pageWidth - 14 });
      if (y + h > doc.page.height - 70) {
        doc.addPage();
        y = 56;
      }
      doc.circle(50, y + 4, 1.6).fill(ACCENT);
      doc.text(note, 58, y, { width: pageWidth - 14 });
      y += h + 6;
    }
  }

  const range = doc.bufferedPageRange();
  for (let i = range.start; i < range.start + range.count; i++) {
    doc.switchToPage(i);
    const fy = doc.page.height - 42;
    doc.rect(46, fy, pageWidth, 0.8).fill(LINE);
    doc.fillColor(MUTED).fontSize(7).font('Helvetica');
    doc.text(model.meta.provenance, 46, fy + 6, { width: pageWidth - 70, lineBreak: false, ellipsis: true });
    doc.text(`Page ${i + range.start + 1} of ${range.start + range.count}`, 46, fy + 16, {
      width: pageWidth,
      align: 'right',
    });
  }

  doc.end();
  return {
    body: await finished,
    mime: REPORT_FORMATS_MIME.pdf,
    extension: 'pdf',
    filename: `${baseName(model)}.pdf`,
  };
};

function drawSection(doc: PDFKit.PDFDocument, section: ReportSection, startY: number, pageWidth: number): number {
  let y = startY;

  const header = () => {
    doc.fillColor(INK).font('Helvetica-Bold').fontSize(10.5).text(section.heading, 46, y, { width: pageWidth });
    y += 15;
    if (section.note) {
      doc.fillColor(MUTED).font('Helvetica-Oblique').fontSize(7.5).text(section.note, 46, y, { width: pageWidth });
      y += doc.heightOfString(section.note, { width: pageWidth }) + 4;
    }
    y += 3;
  };

  header();

  const columns = section.columns;
  // Distribute the page width proportionally to declared widths, with a floor.
  const weights = columns.map((c) => c.width ?? Math.max(10, Math.min(34, c.label.length + 8)));
  const totalWeight = weights.reduce((a, b) => a + b, 0);
  const widths = weights.map((w) => Math.max(46, (w / totalWeight) * pageWidth));
  const scale = pageWidth / widths.reduce((a, b) => a + b, 0);
  const finalWidths = widths.map((w) => w * scale);

  // Column header row
  doc.roundedRect(46, y, pageWidth, 16, 3).fill('#f5f3ff');
  doc.fillColor(INK).font('Helvetica-Bold').fontSize(6.8);
  let x = 46;
  columns.forEach((c, i) => {
    doc.text(c.label.toUpperCase(), x + 4, y + 5, {
      width: finalWidths[i]! - 8,
      align: c.align === 'right' ? 'right' : c.align === 'center' ? 'center' : 'left',
      ellipsis: true,
      lineBreak: false,
    });
    x += finalWidths[i]!;
  });
  y += 16;

  const maxRows = 400;
  section.rows.slice(0, maxRows).forEach((row, rowIndex) => {
    const cells = columns.map((c) => String(row[c.key] ?? ''));
    const heights = cells.map((v, i) =>
      doc.heightOfString(v, { width: finalWidths[i]! - 8, ellipsis: true }),
    );
    const rowH = Math.min(Math.max(Math.max(...heights, 0) + 6, 12), 44);

    if (y + rowH > doc.page.height - 60) {
      doc.addPage();
      y = 46;
      header();
    }

    if (rowIndex % 2 === 1) {
      doc.rect(46, y, pageWidth, rowH).fill('#fafafa');
    }

    let cx = 46;
    cells.forEach((v, i) => {
      doc.fillColor('#0f172a').font('Helvetica').fontSize(7.2);
      doc.text(v, cx + 4, y + 4, {
        width: finalWidths[i]! - 8,
        align: columns[i]!.align === 'right' ? 'right' : columns[i]!.align === 'center' ? 'center' : 'left',
        ellipsis: true,
        lineBreak: rowH > 16,
      });
      cx += finalWidths[i]!;
    });
    doc.moveTo(46, y + rowH).lineTo(46 + pageWidth, y + rowH).lineWidth(0.4).strokeColor(LINE).stroke();
    y += rowH;
  });

  if (section.rows.length > maxRows) {
    doc.fillColor(MUTED).font('Helvetica-Oblique').fontSize(7);
    doc.text(`... ${section.rows.length - maxRows} further rows truncated in this rendering. Use the CSV or XLSX export for the complete extract.`, 46, y + 4, { width: pageWidth });
    y += 16;
  }

  return y + 14;
}

