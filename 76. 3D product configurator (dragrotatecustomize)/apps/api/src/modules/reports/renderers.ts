export const renderJson: ReportRenderer = (model) => {
  const body = Buffer.from(
    JSON.stringify(
      {
        $schema: 'https://prismforge.example/schemas/report-model-1.0.0.json',
        ...model,
      },
      null,
      2,
    ),
    'utf8',
  );
  return {
    body,
    mime: REPORT_FORMATS_MIME.json,
    extension: 'json',
    filename: `${baseName(model)}.json`,
  };
};

// ---------------------------------------------------------------------------
// CSV  (RFC 4180)
// ---------------------------------------------------------------------------

function csvEscape(value: string): string {
  if (/[",\r\n]/.test(value)) return `"${value.replace(/"/g, '""')}"`;
  return value;
}

export const renderCsv: ReportRenderer = (model) => {
  const lines: string[] = [];

  lines.push(csvEscape(`# ${model.meta.title}`));
  lines.push(csvEscape(`# Organisation,${model.meta.organisation}`));
  lines.push(csvEscape(`# Generated at (UTC),${model.meta.generatedAt}`));
  lines.push(csvEscape(`# Generated by,${model.meta.generatedBy.email} (${model.meta.generatedBy.role})`));
  lines.push(csvEscape(`# Correlation id,${model.meta.correlationId}`));
  lines.push(csvEscape(`# Classification,${model.meta.classification}`));
  lines.push(csvEscape(`# Schema version,${model.schemaVersion}`));
  lines.push(csvEscape(`# ${model.meta.provenance}`));
  lines.push('');

  lines.push('SUMMARY');
  lines.push(csvEscape('Field,Value'));
  for (const h of model.headline) lines.push(`${csvEscape(h.label)},${csvEscape(cellText(h.value))}`);
  lines.push('');

  for (const section of model.sections) {
    lines.push(csvEscape(`## ${section.heading}`));
    if (section.note) lines.push(csvEscape(`# ${section.note}`));
    lines.push(section.columns.map((c) => csvEscape(c.label)).join(','));
    for (const row of section.rows) {
      lines.push(section.columns.map((c) => csvEscape(cellText(row[c.key] ?? ''))).join(','));
    }
    lines.push('');
  }

  if (model.notes.length) {
    lines.push(csvEscape('NOTES'));
    for (const n of model.notes) lines.push(csvEscape(`- ${n}`));
    lines.push('');
  }

  // UTF-8 BOM so Excel detects the encoding and renders sRGB hex codes correctly.
  const body = Buffer.concat([Buffer.from([0xef, 0xbb, 0xbf]), Buffer.from(lines.join('\r\n'), 'utf8')]);
  return { body, mime: REPORT_FORMATS_MIME.csv, extension: 'csv', filename: `${baseName(model)}.csv` };
};

